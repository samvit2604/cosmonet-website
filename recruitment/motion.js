function sampleFrames(samples, time) {
  const frame = Math.min(samples.length - 1, Math.max(0, time * FRAME_RATE));
  const i = Math.floor(frame), j = Math.min(i + 1, samples.length - 1);
  return samples[i] + (samples[j] - samples[i]) * (frame - i);
}

// Cubic Hermite tangents follow the quarter-second observations without adding
// overshoot at turning points. The shorter final observation interval is retained.
function lensSlope(i) {
  const last = lensTimes.length - 1;
  if (i === 0) return (lensY[1] - lensY[0]) / (lensTimes[1] - lensTimes[0]);
  if (i === last) return (lensY[last] - lensY[last - 1]) / (lensTimes[last] - lensTimes[last - 1]);
  const before = (lensY[i] - lensY[i - 1]) / (lensTimes[i] - lensTimes[i - 1]);
  const after = (lensY[i + 1] - lensY[i]) / (lensTimes[i + 1] - lensTimes[i]);
  if (before * after <= 0) return 0;
  return 2 * before * after / (before + after);
}

function sampleLensY(time) {
  const last = lensTimes.length - 1;
  if (time <= lensTimes[0]) return lensY[0];
  if (time >= lensTimes[last]) return lensY[last];
  let i = 0;
  while (time > lensTimes[i + 1]) i++;
  const span = lensTimes[i + 1] - lensTimes[i];
  const t = (time - lensTimes[i]) / span, t2 = t * t, t3 = t2 * t;
  return (2 * t3 - 3 * t2 + 1) * lensY[i]
    + (t3 - 2 * t2 + t) * span * lensSlope(i)
    + (-2 * t3 + 3 * t2) * lensY[i + 1]
    + (t3 - t2) * span * lensSlope(i + 1);
}

function referenceAt(time) {
  return {
    lensX: sampleFrames(lensX, time),
    lensY: sampleLensY(time),
    cardTop: sampleFrames(cardTop, time),
    approvalBrightness: sampleFrames(approvalBrightness, time),
  };
}

const first = referenceAt(0), last = referenceAt(REFERENCE_DURATION);

/** Return the reference's image-space motion in pixels, plus normalised brightness. */
export function sampleReferenceMotion(time) {
  const t = Number.isFinite(time) ? ((time % LOOP_DURATION) + LOOP_DURATION) % LOOP_DURATION : 0;
  if (t <= REFERENCE_DURATION) return referenceAt(t);
  const progress = (t - REFERENCE_DURATION) / (LOOP_DURATION - REFERENCE_DURATION);
  const blend = progress * progress * (3 - 2 * progress);
  return {
    lensX: last.lensX + (first.lensX - last.lensX) * blend,
    lensY: last.lensY + (first.lensY - last.lensY) * blend,
    cardTop: last.cardTop + (first.cardTop - last.cardTop) * blend,
    approvalBrightness: last.approvalBrightness + (first.approvalBrightness - last.approvalBrightness) * blend,
  };
}
